// Builds the airline library (onay 2026-10-24, Emre: "havayolu önerini kabul ediyorum"): every logo of the airlogos package
// (MIT) as static/logos/airlines/<IATA>.png, and src/lib/airlineData.ts with those codes and the active airlines' names
// from OpenFlights' airlines.dat (ODbL). Run once when either source changes:
// node scripts/airline-data.mjs <airlogos dist/index.js> <openflights airlines.dat>
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const [logosJs, dat] = process.argv.slice(2);
const require = createRequire(import.meta.url);
const raw = require(logosJs);
const logos = raw.default ?? raw;
mkdirSync("static/logos/airlines", { recursive: true });
const codes = [];
for (const [code, v] of Object.entries(logos)) {
  const m = typeof v.png === "string" ? v.png.match(/^data:image\/png;base64,(.+)$/) : null;
  if (!m || !/^[A-Z0-9]{2}$/.test(code)) continue;
  writeFileSync(`static/logos/airlines/${code}.png`, Buffer.from(m[1], "base64"));
  codes.push(code);
}
codes.sort();

// airlines.dat: id, name, alias, IATA, ICAO, callsign, country, active
const parse = (line) => {
  const out = [];
  let cur = "", q = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (q) {
      if (ch === '"' && line[i + 1] === '"') (cur += '"'), i++;
      else if (ch === '"') q = false;
      else cur += ch;
    } else if (ch === '"') q = true;
    else if (ch === ",") out.push(cur), (cur = "");
    else cur += ch;
  }
  out.push(cur);
  return out;
};
const byCode = new Map();
for (const line of readFileSync(dat, "utf8").split("\n")) {
  const r = parse(line);
  if (r.length < 8 || r[7] !== "Y" || !/^[A-Z0-9]{2}$/.test(r[3]) || !r[1] || /^(unknown|private flight)$/i.test(r[1])) continue;
  const list = byCode.get(r[3]) ?? [];
  list.push(r[1].trim());
  byCode.set(r[3], list);
}
const names = [];
for (const [code, list] of [...byCode].sort()) for (const n of new Set(list)) names.push([n, code]);
writeFileSync(
  "src/lib/airlineData.ts",
  `// Generated by scripts/airline-data.mjs: do not edit by hand. Logos: airlogos 1.0.7 (MIT, static/licenses/airlogos-MIT.txt).
// Names: OpenFlights airlines.dat, active airlines with an IATA code (ODbL, static/licenses/openflights-ODbL.txt).

/** The airlines whose logo is in the extension (static/logos/airlines/<code>.png). */
export const LOGO_CODES = ${JSON.stringify(codes.join(" "))};

/** [name, IATA code] of the active airlines. */
export const AIRLINE_NAMES: readonly (readonly [string, string])[] = ${JSON.stringify(names)};
`,
);
console.log(JSON.stringify({ logos: codes.length, names: names.length }));
